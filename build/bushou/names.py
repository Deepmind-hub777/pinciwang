def name_of(form,pos,main_is_left_ear=None):
    """pos in {'L','R','T','B','O','X'} : 左/右/上/下/外框/其他"""
    if form=='阝':
        return '左耳旁' if main_is_left_ear else '右耳旁'
    if form in FIXED: return FIXED[form]
    base=SIDE.get(form)
    if pos=='L' and base and base.endswith('旁'): return base
    if pos=='L' and base: return base
    if pos=='T': return form+'字头'
    if pos=='B': return form+'字底'
    if pos=='L': return form+'字旁'
    return form+'部'
